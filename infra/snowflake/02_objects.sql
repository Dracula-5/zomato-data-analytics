-- Schemas, the stage over the lake, and read-only access for analysts. Safe to run again.
USE DATABASE {{ database }};

CREATE SCHEMA IF NOT EXISTS RAW;
CREATE SCHEMA IF NOT EXISTS STAGING;
CREATE SCHEMA IF NOT EXISTS SNAPSHOTS;

-- Managed access lets the schema owner set the future grants below, so ZAP_DEPLOYER doesn't
-- need the account-wide MANAGE GRANTS privilege. It has to be set at creation: turning it on
-- later needs that same privilege.
CREATE SCHEMA IF NOT EXISTS MARTS WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS GOVERNANCE WITH MANAGED ACCESS;

CREATE FILE FORMAT IF NOT EXISTS RAW.PARQUET_FMT
  TYPE = PARQUET
  USE_LOGICAL_TYPE = TRUE
  USE_VECTORIZED_SCANNER = TRUE;

CREATE STAGE IF NOT EXISTS RAW.LAKE
  URL = 's3://{{ bucket }}/'
  STORAGE_INTEGRATION = ZAP_S3
  FILE_FORMAT = RAW.PARQUET_FMT;

-- Analysts read the marts and governance tables; RAW and STAGING stay private.
GRANT USAGE ON DATABASE {{ database }} TO ROLE ZAP_ANALYST;
GRANT USAGE ON SCHEMA MARTS TO ROLE ZAP_ANALYST;
GRANT USAGE ON SCHEMA GOVERNANCE TO ROLE ZAP_ANALYST;
GRANT SELECT ON ALL TABLES IN SCHEMA MARTS TO ROLE ZAP_ANALYST;
GRANT SELECT ON FUTURE TABLES IN SCHEMA MARTS TO ROLE ZAP_ANALYST;
GRANT SELECT ON ALL TABLES IN SCHEMA GOVERNANCE TO ROLE ZAP_ANALYST;
GRANT SELECT ON FUTURE TABLES IN SCHEMA GOVERNANCE TO ROLE ZAP_ANALYST;
