"""Render docs/DATA_DICTIONARY.md from dbt's manifest + catalog and the schema contracts.

Sources come from the contracts (with each column's classification). Models come from dbt:
column types from the catalog (what the warehouse actually built), descriptions and meta
from the YAML, and the tests attached to each column from the manifest.
"""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path
from typing import Any

from zap.ingest.contracts import Contract

SCHEMA_ORDER = ["marts", "governance", "staging", "snapshots"]


def _cell(text: Any) -> str:
    return " ".join(str(text or "").split()).replace("|", "\\|")


def _tests_by_column(manifest: dict[str, Any]) -> dict[tuple[str, str], list[str]]:
    tests: dict[tuple[str, str], list[str]] = defaultdict(list)
    for node in manifest.get("nodes", {}).values():
        if node.get("resource_type") != "test" or not node.get("column_name"):
            continue
        meta = node.get("test_metadata") or {}
        name = meta.get("name") or node.get("name", "")
        attached = node.get("attached_node")
        if attached:
            tests[(attached, node["column_name"])].append(str(name))
    return tests


def render_dictionary(
    manifest: dict[str, Any], catalog: dict[str, Any], contracts: dict[str, Contract]
) -> str:
    lines = [
        "# Data dictionary",
        "",
        "Generated by `make docs` from the dbt manifest and catalog and the schema contracts.",
        "Do not edit by hand. Classification: `public`, `internal`, `pii`, `secret`.",
        "",
        "## Sources (raw layer)",
        "",
    ]
    for c in contracts.values():
        lines += [
            f"### raw.{c.table}",
            "",
            _cell(c.description),
            "",
            "| Column | Type | Classification | Description |",
            "|---|---|---|---|",
        ]
        lines += [
            f"| {col.name} | {col.type} | {col.classification} | {_cell(col.description)} |"
            for col in c.columns
        ]
        lines.append("")

    tests = _tests_by_column(manifest)
    catalog_nodes = {**catalog.get("nodes", {}), **catalog.get("snapshots", {})}
    by_schema: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for uid, node in manifest.get("nodes", {}).items():
        if node.get("resource_type") in ("model", "snapshot"):
            by_schema[str(node.get("schema"))].append({"uid": uid, **node})

    for schema in sorted(
        by_schema, key=lambda s: SCHEMA_ORDER.index(s) if s in SCHEMA_ORDER else 99
    ):
        lines += [f"## {schema}", ""]
        for node in sorted(by_schema[schema], key=lambda n: n["name"]):
            built = catalog_nodes.get(node["uid"], {}).get("columns", {})
            documented = {k.lower(): v for k, v in node.get("columns", {}).items()}
            materialized = node.get("config", {}).get("materialized", node["resource_type"])
            lines += [
                f"### {schema}.{node['name']}",
                "",
                f"*{materialized}*. {_cell(node.get('description')) or '(no description)'}",
                "",
                "| Column | Type | Classification | Tests | Description |",
                "|---|---|---|---|---|",
            ]
            names = [c["name"] for c in sorted(built.values(), key=lambda c: c.get("index", 0))]
            for name in names or list(documented):
                doc = documented.get(name.lower(), {})
                col_type = built.get(name, {}).get("type", doc.get("data_type", ""))
                klass = (doc.get("meta") or {}).get("classification", "")
                col_tests = ", ".join(sorted(set(tests.get((node["uid"], name), []))))
                lines.append(
                    f"| {name} | {col_type} | {klass} | {col_tests} | "
                    f"{_cell(doc.get('description'))} |"
                )
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def write_dictionary(target: Path, contracts: dict[str, Contract], out: Path) -> Path:
    """`target` is the dbt artifacts folder of the dataset that ran `dbt docs generate`."""
    manifest = json.loads((target / "manifest.json").read_text(encoding="utf-8"))
    catalog = json.loads((target / "catalog.json").read_text(encoding="utf-8"))
    out.parent.mkdir(parents=True, exist_ok=True)
    text = render_dictionary(manifest, catalog, contracts)
    out.write_text(text, encoding="utf-8", newline="\n")  # LF on every OS, like git
    return out
