"""Turn collected metrics into docs/METRICS.md."""

from __future__ import annotations

from itertools import groupby
from pathlib import Path

from zap.metrics.collect import NOT_RUN, Metric

HEADER = """# Metrics

Generated by `make metrics` from the files real runs left behind. Don't edit this by hand.
A value of "not run" means no run has produced it yet. Nothing here is estimated.

The source data is **synthetic-looking**: it behaves like generated data, so results describe
this dataset rather than real food delivery. Anything marked SYNTHETIC used events planted on
purpose to test a detector. The 5% sample is by user, and keeps each user's whole history.
"""


def render(metrics: list[Metric]) -> str:
    lines = [HEADER]
    done = sum(metric.value != NOT_RUN for metric in metrics)
    lines.append(f"**{done} of {len(metrics)} metrics have been measured.**\n")
    for group, rows in groupby(metrics, key=lambda metric: metric.group):
        lines += [
            f"## {group}\n",
            "| Metric | Value | Data | Source | Ran |",
            "|---|---|---|---|---|",
        ]
        lines += [
            f"| {m.name} | **{m.value}** | {m.data} | `{m.source}` | {m.ran_at} |" for m in rows
        ]
        lines.append("")
    return "\n".join(lines)


def write(metrics: list[Metric], path: Path) -> None:
    path.write_text(render(metrics), encoding="utf-8", newline="\n")
